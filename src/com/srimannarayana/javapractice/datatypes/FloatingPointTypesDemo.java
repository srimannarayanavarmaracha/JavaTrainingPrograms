package com.srimannarayana.javapractice.datatypes;

public class FloatingPointTypesDemo {

	public static void main(String[] args) {
		
		//float
		float floatValue = 99.99F;
		
		//double
		double doubleValue = 99999.999999;
		
		final double PI_VALUE = 3.14159;
		
		System.out.println("========= Floating-Point Types =========");
		
		System.out.println("\nFloat Value : " + floatValue);
		
		System.out.println("\nDouble Value : " + doubleValue);
		
		System.out.println("\nPI_VALUE : " + PI_VALUE);
		
	}

}