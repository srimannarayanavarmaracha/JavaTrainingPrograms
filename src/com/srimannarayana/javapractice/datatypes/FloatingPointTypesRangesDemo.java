package com.srimannarayana.javapractice.datatypes;

public class FloatingPointTypesRangesDemo {

	public static void main(String[] args) {
		
		System.out.println("======== Floating Point Types Ranges =========");
		
		System.out.println("\nFLOAT :");
		System.out.println("Minimum Value : " + Float.MIN_VALUE);
		System.out.println("Maximum Value : " + Float.MAX_VALUE);
		System.out.println("Minimum Normal :" + Float.MIN_NORMAL);
		System.out.println("Maximum Exponent : " + Float.MAX_EXPONENT);
		System.out.println("Negitive Infinity : " + Float.NEGATIVE_INFINITY);
		System.out.println("Positive Infinity : " + Float.POSITIVE_INFINITY);
		System.out.println("NaN : " + Float.NaN);
		System.out.println("Precision : " + Float.PRECISION);
		System.out.println("Bytes : " + Float.BYTES);
		
		System.out.println("\nDOUBLE :");
		System.out.println("Minimum : " + Double.MIN_VALUE);
		System.out.println("Maximum : " + Double.MAX_VALUE);
		System.out.println("Minimum Normal : " + Double.MIN_NORMAL);
		System.out.println("Maximum Exponent : " + Double.MAX_EXPONENT);
		System.out.println("Negitive Infinity : " + Double.NEGATIVE_INFINITY);
		System.out.println("Positive Infinity : " + Double.POSITIVE_INFINITY);
		System.out.println("NaN : " + Double.NaN);
		System.out.println("Precision : " + Double.PRECISION);
		System.out.println("Bytes " + Double.BYTES);
		
	}

}